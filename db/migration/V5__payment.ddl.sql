-- V5: 계약금 온라인 결제 (토스페이먼츠 결제위젯) 2026-11-24
-- 추가만 함 (기존 테이블 · 데이터는 건드리지 않음). TBL_RESERVATION.PAY_STATUS / DEPOSIT_PAID_AT 는 그대로 쓰고,
-- 결제 한 건의 주문번호 · 결제키(환불에 필요) · 금액 · 수단 · 영수증을 여기에 남김.

CREATE SEQUENCE SEQ_PAYMENT START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TBL_PAYMENT (
	PAYMENT_ID     NUMBER(19) NOT NULL,
	RESERVATION_ID NUMBER(19) NOT NULL,
	MEMBER_ID      NUMBER(19) NOT NULL,
	ORDER_ID       VARCHAR2(64 CHAR) NOT NULL,
	ORDER_NAME     VARCHAR2(100 CHAR) NOT NULL,
	AMOUNT         NUMBER(12) NOT NULL,
	PAY_TYPE       CHAR(2) DEFAULT '01' NOT NULL,
	STATUS         CHAR(2) DEFAULT '01' NOT NULL,
	PAYMENT_KEY    VARCHAR2(200 CHAR),
	METHOD         VARCHAR2(50 CHAR),
	RECEIPT_URL    VARCHAR2(500 CHAR),
	FAIL_CODE      VARCHAR2(60 CHAR),
	FAIL_MESSAGE   VARCHAR2(300 CHAR),
	REQUESTED_AT   DATE DEFAULT SYSDATE NOT NULL,
	APPROVED_AT    DATE,
	CANCELLED_AT   DATE,
	CONSTRAINT PK_PAYMENT PRIMARY KEY (PAYMENT_ID),
	CONSTRAINT UK_PAYMENT_ORDER UNIQUE (ORDER_ID),
	CONSTRAINT FK_PAYMENT_RESERVATION FOREIGN KEY (RESERVATION_ID) REFERENCES TBL_RESERVATION (RESERVATION_ID),
	CONSTRAINT CK_PAYMENT_STATUS CHECK (STATUS IN ('01', '02', '03', '04')),
	CONSTRAINT CK_PAYMENT_TYPE CHECK (PAY_TYPE IN ('01'))
);

CREATE INDEX IX_PAYMENT_RESERVATION ON TBL_PAYMENT (RESERVATION_ID);

COMMENT ON TABLE TBL_PAYMENT IS '계약금 온라인 결제 (토스페이먼츠)';
COMMENT ON COLUMN TBL_PAYMENT.ORDER_ID IS '우리가 만든 주문번호 (영문 · 숫자 · - _ = , 6~64자)';
COMMENT ON COLUMN TBL_PAYMENT.PAY_TYPE IS '01 계약금';
COMMENT ON COLUMN TBL_PAYMENT.STATUS IS '01 결제 대기 · 02 결제 완료 · 03 실패 · 04 결제 취소(환불)';
COMMENT ON COLUMN TBL_PAYMENT.PAYMENT_KEY IS '토스페이먼츠 결제 키 (조회 · 취소에 필요)';
COMMENT ON COLUMN TBL_PAYMENT.METHOD IS '결제 수단 (카드 · 간편결제(카카오페이 등) · 계좌이체 …)';
