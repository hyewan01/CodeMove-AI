-- ---------- TBL_ITEM : 표준 품목 ----------
-- AI 프롬프트에 이 목록을 넣고, AI 는 이 품목 중에서만 고르게 함
CREATE TABLE TBL_ITEM (
	ITEM_ID     NUMBER(19) NOT NULL,
	ITEM_NAME   VARCHAR2(50 CHAR) NOT NULL,
	CATEGORY    CHAR(2) NOT NULL,
	OPTION_CODE CHAR(2),
	SORT_ORDER  NUMBER(5) DEFAULT 0 NOT NULL,
