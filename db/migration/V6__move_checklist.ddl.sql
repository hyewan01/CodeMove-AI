-- V6: 고객 이사 준비 체크리스트 2026-11-24
-- 추가만 함. 기본 항목 내용은 src/main/resources/checklist/move-checklist.csv (코드 M01…)에 두고,
-- 여기에는 고객이 체크한 상태와 고객이 직접 넣은 할 일만 남김. 이사(요청)마다 따로 (REQUEST_ID, 요청 전이면 0).

CREATE SEQUENCE SEQ_MOVE_CHECKLIST START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TBL_MOVE_CHECKLIST (
	CHECK_ID    NUMBER(19) NOT NULL,
	MEMBER_ID   NUMBER(19) NOT NULL,
	REQUEST_ID  NUMBER(19) DEFAULT 0 NOT NULL,
	ITEM_CODE   VARCHAR2(20 CHAR),
	PHASE       CHAR(2) NOT NULL,
	TITLE       VARCHAR2(100 CHAR),
	DONE_YN     CHAR(1) DEFAULT 'N' NOT NULL,
	CREATED_AT  DATE DEFAULT SYSDATE NOT NULL,
	DONE_AT     DATE,
	CONSTRAINT PK_MOVE_CHECKLIST PRIMARY KEY (CHECK_ID),
	CONSTRAINT CK_MOVE_CHECKLIST_DONE CHECK (DONE_YN IN ('Y', 'N')),
	CONSTRAINT CK_MOVE_CHECKLIST_PHASE CHECK (PHASE IN ('01', '02', '03', '04', '05', '06', '07')),
	CONSTRAINT CK_MOVE_CHECKLIST_ITEM CHECK (ITEM_CODE IS NOT NULL OR TITLE IS NOT NULL)
);

CREATE INDEX IX_MOVE_CHECKLIST_MEMBER ON TBL_MOVE_CHECKLIST (MEMBER_ID, REQUEST_ID);

COMMENT ON TABLE TBL_MOVE_CHECKLIST IS '고객 이사 준비 체크리스트 (체크 상태 · 직접 추가한 할 일)';
COMMENT ON COLUMN TBL_MOVE_CHECKLIST.ITEM_CODE IS '기본 항목 코드 (move-checklist.csv), 고객이 넣은 할 일이면 NULL';
COMMENT ON COLUMN TBL_MOVE_CHECKLIST.PHASE IS '01 한 달 전 · 02 열흘 전 · 03 사흘 전 · 04 전날 · 05 당일 출발지 · 06 당일 도착지 · 07 이사 후';
COMMENT ON COLUMN TBL_MOVE_CHECKLIST.TITLE IS '고객이 직접 넣은 할 일 (기본 항목이면 NULL)';
