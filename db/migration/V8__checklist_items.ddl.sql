-- 추가만 함. 처음 비어 있으면 앱이 src/main/resources/checklist/move-checklist.csv 내용을 한 번 넣음 (ChecklistService).
-- 고객 체크 상태(TBL_MOVE_CHECKLIST.ITEM_CODE)는 이 표의 ITEM_CODE 를 가리킴.

CREATE TABLE TBL_CHECKLIST_ITEM (
	ITEM_CODE   VARCHAR2(20 CHAR) NOT NULL,
	PHASE       CHAR(2) NOT NULL,
	TITLE       VARCHAR2(100 CHAR) NOT NULL,
	DETAIL      VARCHAR2(500 CHAR),
	WHERE_TEXT  VARCHAR2(100 CHAR),
	LINK_URL    VARCHAR2(200 CHAR),
	SORT_NO     NUMBER(5) DEFAULT 0 NOT NULL,
	USE_YN      CHAR(1) DEFAULT 'Y' NOT NULL,
	UPDATED_AT  DATE DEFAULT SYSDATE NOT NULL,
	CONSTRAINT PK_CHECKLIST_ITEM PRIMARY KEY (ITEM_CODE),
	CONSTRAINT CK_CHECKLIST_ITEM_USE CHECK (USE_YN IN ('Y', 'N')),
	CONSTRAINT CK_CHECKLIST_ITEM_PHASE CHECK (PHASE IN ('01', '02', '03', '04', '05', '06', '07'))
);

COMMENT ON TABLE TBL_CHECKLIST_ITEM IS '이사 준비 체크리스트 기본 항목 (관리자가 수정)';
COMMENT ON COLUMN TBL_CHECKLIST_ITEM.PHASE IS '01 한 달 전 · 02 열흘 전 · 03 사흘 전 · 04 전날 · 05 당일 출발지 · 06 당일 도착지 · 07 이사 후';
COMMENT ON COLUMN TBL_CHECKLIST_ITEM.WHERE_TEXT IS '어디서 (예: 주민센터)';
COMMENT ON COLUMN TBL_CHECKLIST_ITEM.LINK_URL IS '바로가기 (앱 안 경로 / 로 시작, 또는 https 주소)';
COMMENT ON COLUMN TBL_CHECKLIST_ITEM.USE_YN IS 'N 이면 고객 화면에서 숨김';
