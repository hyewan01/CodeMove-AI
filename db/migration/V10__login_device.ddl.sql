-- V10: 로그인 유지 (이 기기에서는 문자 인증 없이 다시 로그인) 2026-11-25
-- 추가만 함 (새 표 하나). 토큰 원문은 고객 브라우저 쿠키에만 있고, 여기에는 SHA-256 값만 둠.

CREATE SEQUENCE SEQ_LOGIN_DEVICE START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE TBL_LOGIN_DEVICE (
	DEVICE_ID   NUMBER(19) NOT NULL,
	MEMBER_ID   NUMBER(19) NOT NULL,
	TOKEN_HASH  VARCHAR2(64 CHAR) NOT NULL,
	CREATED_AT  DATE DEFAULT SYSDATE NOT NULL,
	EXPIRES_AT  DATE NOT NULL,
	CONSTRAINT PK_LOGIN_DEVICE PRIMARY KEY (DEVICE_ID),
	CONSTRAINT UK_LOGIN_DEVICE_TOKEN UNIQUE (TOKEN_HASH)
);

CREATE INDEX IX_LOGIN_DEVICE_MEMBER ON TBL_LOGIN_DEVICE (MEMBER_ID);

COMMENT ON TABLE TBL_LOGIN_DEVICE IS '고객 로그인 유지 기기 (30일). 관리자는 쓰지 않음';
COMMENT ON COLUMN TBL_LOGIN_DEVICE.TOKEN_HASH IS '쿠키 토큰의 SHA-256 (원문은 저장하지 않음)';
