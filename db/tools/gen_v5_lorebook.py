TOPIC_TYPE_GUIDE = '01'


def q(s):
    """Oracle 대체 인용 q'[...]' (내용에 ]' 가 없어야 함)"""
    assert "]'" not in s
    return "q'[" + s + "]'"


def main():
    lines = [
        '-- ==================================================',
        '-- V5 챗봇 로어북 기본 내용 (2026-11-21) : 자동 생성 파일, 직접 고치지 말고',
        '--   db/tools/gen_v5_lorebook.py 를 고친 뒤 py -3 db/tools/gen_v5_lorebook.py',
        '-- 추가만 함: 같은 제목의 주제가 있으면 그 주제를 쓰고, 같은 키워드의 로어북은 다시 넣지 않음.',
        '-- 기존 로어북은 바꾸거나 지우지 않음. 관리자 화면(AI 챗봇 답변 관리)에서 계속 고칠 수 있음.',
        '-- 각 문장은 / 로 끝남 (SQL*Plus · SQL Developer 스크립트 실행)',
        '-- ==================================================',
        '',
    ]
    count = 0
    for title, intro, books in TOPICS:
        assert len(title) <= 50 and len(intro) <= 200
        lines += [
            f'-- ---------- {title} ----------',
            'INSERT INTO TBL_CHATBOT_TOPIC (TOPIC_ID, TITLE, INTRO, TOPIC_TYPE, IS_ACTIVE, UPDATED_AT)',
            f"SELECT SEQ_CHATBOT_TOPIC.NEXTVAL, {q(title)}, {q(intro)}, '{TOPIC_TYPE_GUIDE}', 'Y', SYSDATE FROM DUAL",
            f' WHERE NOT EXISTS (SELECT 1 FROM TBL_CHATBOT_TOPIC WHERE TITLE = {q(title)})',
            '/',
        ]
        topic = f'(SELECT MIN(TOPIC_ID) FROM TBL_CHATBOT_TOPIC WHERE TITLE = {q(title)})'
        for i, (kw, content) in enumerate(books, 1):
            assert len(kw) <= 200, kw
            assert len(content) <= 1000, (len(content), content[:30])
            assert ';' not in content
            lines += [
                'INSERT INTO TBL_LOREBOOK (LOREBOOK_ID, TOPIC_ID, KEYWORDS, CONTENT, SORT_ORDER, UPDATED_AT)',
                f'SELECT SEQ_LOREBOOK.NEXTVAL, {topic}, {q(kw)},',
                f'       {q(content)},',
                f'       (SELECT NVL(MAX(SORT_ORDER), 0) + 1 FROM TBL_LOREBOOK WHERE TOPIC_ID = {topic}), SYSDATE FROM DUAL',
                f' WHERE NOT EXISTS (SELECT 1 FROM TBL_LOREBOOK WHERE TOPIC_ID = {topic} AND KEYWORDS = {q(kw)})',
                '/',
            ]
            count += 1
        lines.append('')
    lines += ['COMMIT', '/', '']
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'topics {len(TOPICS)}, lorebooks {count} -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
